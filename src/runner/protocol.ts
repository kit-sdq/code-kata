// postMessage protocol between the main app and the sandbox iframe (public/sandbox.html).
// A2 defines the shapes; A4 implements the sandbox side against them.
import type { Check } from '../kata/types.ts';

export interface RunRequestMessage {
  type: 'run';
  requestId: string;
  source: string;
  mainClass: string;
  checks: Check[];
  timeoutMs: number;
  harnessSource: string; // generated by src/runner/harness.ts, compiled as KataRunner.java
}

export interface StopMessage { type: 'stop'; requestId: string }

export type HostMessage = RunRequestMessage | StopMessage;

export type Phase = 'loading' | 'compiling' | 'running';

export interface PhaseMessage { type: 'phase'; requestId: string; phase: Phase }

export interface ResultMessage {
  type: 'result';
  requestId: string;
  result:
    | { status: 'ok'; stdout: string; returns: { json: string }[] }
    | { status: 'compile-error' | 'runtime-error' | 'error'; message: string }
    | { status: 'timeout' }
    | { status: 'stopped' };
}

export type SandboxMessage = PhaseMessage | ResultMessage;
